def get_phase(day: date) -> CanonPhase | None:
    for phase in PHASES:
        if phase.start <= day <= phase.end:
            return phase
    return None


def canon_hint(day: date, side: str | None = None) -> str:
    lines = [
        f"{WAR_NAME}: {WAR_START.strftime('%d.%m.%Y')} - {WAR_END.strftime('%d.%m.%Y')}",
        f"Текущая дата: {day.strftime('%d.%m.%Y')}",
    ]
    phase = get_phase(day)
    if phase is None:
        if day < WAR_START:
            lines.append("Сейчас дата до начала войны. Канонно идет предвоенная подготовка, а не полноценное наступление.")
        else:
            lines.append("Сейчас дата уже после официального завершения войны. Канонно больших наступлений больше нет.")
        return "\n".join(lines)

    lines.append(f"Фаза: {phase.title}")
    if side is None or side == "kefir":
        lines.append(f"Кефирстан: {phase.kefir}")
    if side is None or side == "yogurt":
        lines.append(f"Йогуртстан: {phase.yogurt}")
    lines.append(f"Примечание: {phase.note}")
    return "\n\n".join(lines)
